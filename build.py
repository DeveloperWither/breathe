"""Builds the phone breathing app from SSL Coach's Breathe tab, so both stay identical.

Run:  python build.py   -> writes app.js + icons. Then commit and push; GitHub Pages serves it.
"""
import os
from PIL import Image, ImageDraw, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
MIND = os.path.join(HERE, "..", "ssl-coach", "static", "mind.js")

src = open(MIND, encoding="utf-8").read()
start = src.index("// ---------------------------------------------------------------- Breathe tab")
code = src[start:]
code += "\n\n// standalone start\nmBreathe(document.getElementById('app'));\n"
code += "if ('serviceWorker' in navigator) navigator.serviceWorker.register('sw.js').catch(() => {});\n"
with open(os.path.join(HERE, "app.js"), "w", encoding="utf-8") as f:
    f.write("// Generated by build.py from ssl-coach/static/mind.js - edit there, then rebuild.\n" + code)


def icon(size, path, pad=0.0):
    im = Image.new("RGB", (size, size), (8, 11, 20))
    glow = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(glow)
    c, r = size / 2, size * (0.34 - pad)
    d.ellipse([c - r * 1.25, c - r * 1.25, c + r * 1.25, c + r * 1.25], fill=(45, 212, 191, 110))
    glow = glow.filter(ImageFilter.GaussianBlur(size * 0.06))
    im.paste(glow, (0, 0), glow)
    orb = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    od = ImageDraw.Draw(orb)
    steps = 60
    for i in range(steps):  # radial gradient: white-ish centre -> teal -> blue edge
        k = i / steps
        rr = r * (1 - k)
        col = (int(59 + (200 - 59) * k), int(140 + (240 - 140) * k), int(255 - (255 - 230) * k), 255)
        if k < 0.5:
            col = (int(59 + (45 - 59) * k * 2), int(140 + (212 - 140) * k * 2), int(255 + (191 - 255) * k * 2), 255)
        else:
            j = (k - 0.5) * 2
            col = (int(45 + (230 - 45) * j), int(212 + (250 - 212) * j), int(191 + (245 - 191) * j), 255)
        od.ellipse([c - rr, c - rr, c + rr, c + rr], fill=col)
    im.paste(orb, (0, 0), orb)
    ring = ImageDraw.Draw(im)
    rr = size * (0.44 - pad)
    w = max(2, size // 40)
    ring.ellipse([c - rr, c - rr, c + rr, c + rr], outline=(40, 46, 64), width=w)
    ring.arc([c - rr, c - rr, c + rr, c + rr], -90, 160, fill=(129, 140, 248), width=w)
    im.save(path)


icon(192, os.path.join(HERE, "icon-192.png"))
icon(512, os.path.join(HERE, "icon-512.png"))
icon(512, os.path.join(HERE, "icon-maskable.png"), pad=0.08)
icon(180, os.path.join(HERE, "apple-touch-icon.png"))
print("built app.js + icons")
